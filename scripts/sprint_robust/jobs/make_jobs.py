"""Write one job script per recipe (scripts/sprint_robust/jobs/{name}.sh). Run locally: python make_jobs.py
All recipes: fine-tune from v1 (LoRA + heads), STEPS steps, lr 1e-4, same replay (25% of the v1 text/GUI/PixMo
records) + the same augmented natural images; they differ only in the variants / losses below."""
import os

ALL = "zh,para,func,vague,ufunc,ugeneric,absfunc,absgeneric"
ABL = "rg,robust_zh,robust_para,robust_func,robust_vague,refcoco_val,refcocog_val,grefcoco_val_merged"
LM = "w_lm=0.2 lm_file=/content/up/lm_captions.jsonl lm_bs=4"
R = {
    "c0_ctrl":    dict(VARIANTS="none"),                                   # same data/steps, no shifted descriptions
    "r1_zhpara":  dict(VARIANTS="zh,para"),                                # multilingual + paraphrase
    "r2_aug":     dict(VARIANTS=ALL, SETS=ABL),                                      # + functional / vague (+ absent counterparts)
    "r3_cons":    dict(VARIANTS=ALL, TRAIN_SET="w_cons=1.0"),              # + paraphrase-consistency loss
    "r4_lm":      dict(VARIANTS=ALL, TRAIN_SET=f"w_cons=1.0 {LM}"),        # + caption LM loss
    "a_nozh":     dict(VARIANTS="func,vague,ufunc,ugeneric,absfunc,absgeneric", TRAIN_SET="w_cons=1.0", SETS=ABL),  # full - zh/para
    "a_nofunc":   dict(VARIANTS="zh,para", TRAIN_SET="w_cons=1.0", SETS=ABL),        # full - functional/vague
    "a_noabs":    dict(VARIANTS="zh,para,func,vague,ufunc,ugeneric", TRAIN_SET="w_cons=1.0", SETS=ABL),  # full - absent shifted
    "d_heads":    dict(VARIANTS=ALL, LR="0", LR_HEADS="1e-4", SETS=ABL),             # diagnostic: heads only, LoRA frozen
    "r5_teacher": dict(VARIANTS=ALL, TRAIN_SET="w_cons=1.0", MIX_ARGS="--teacher /content/up/teacher_iou.json", SETS=ABL),
}
here = os.path.dirname(os.path.abspath(__file__))
for name, env in R.items():
    env = dict(dict(NAME=name, STEPS="${STEPS:-800}"), **env)
    lines = ["#!/usr/bin/env bash", f"# recipe {name} (generated by make_jobs.py)"]
    lines += [f'export {k}="{v}"' for k, v in env.items()]
    lines += ["while pgrep -f '[b]ase_gen.py|[e]val.py|[t]rain.py' > /dev/null; do sleep 30; done  # one GPU job at a time",
              "bash /content/dv/scripts/sprint_robust/run_recipe.sh"]
    open(f"{here}/{name}.sh", "w").write("\n".join(lines) + "\n")
print(sorted(R))
